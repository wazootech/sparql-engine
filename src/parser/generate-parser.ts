// deno-lint-ignore-file no-import-prefix
/**
 * Regenerates `parser.ts` — a pure ESM TypeScript parser — from the in-repo
 * jison grammar (`sparql.jison`).
 *
 * Mirrors sparqljs@3.7.4's own build step:
 *   jison lib/sparql.jison -p slr -m js -o lib/SparqlParser.js
 *   echo 'module.exports=SparqlParser' >> lib/SparqlParser.js
 *
 * then post-processes the output into ESM/TS:
 *
 *   - inlines `Wildcard` (upstream `lib/Wildcard.js`) so the generated module
 *     has no `require` and the file can be deleted,
 *   - replaces `module.exports=SparqlParser` with a default ESM export,
 *   - prepends `// @ts-nocheck` and `// deno-lint-ignore-file` so the file
 *     needs no `deno.json` fmt/lint excludes (it is generated code),
 *   - runs `deno fmt` so the checked-in artifact is fmt-stable and regenerating
 *     reproduces it byte-for-byte.
 *
 * Run via `deno task parser:generate`. With `--check`, it verifies instead of
 * writing: it exits non-zero when the checked-in `parser.ts` has drifted from
 * the grammar (used by `deno task parser:check` in CI).
 */
import jison from "npm:jison@0.4.18";
import { parse as parseGrammar } from "npm:ebnf-parser@0.1.10";

const GRAMMAR_PATH = new URL("./sparql.jison", import.meta.url);
const OUTPUT_PATH = new URL("./parser.ts", import.meta.url);

// jison@0.4.18 and ebnf-parser@0.1.10 ship no TypeScript types, so their
// surfaces are typed `any` here (guarded by the generation diff in CI).
type JisonModule = {
  Generator: new (
    grammar: Record<string, unknown>,
    options: Record<string, unknown>,
  ) => { generate: (options: Record<string, unknown>) => string };
};
type EbnfParser = { parse: (grammar: string) => Record<string, unknown> };

/**
 * wildcardSource is upstream `lib/Wildcard.js` (sparqljs@3.7.4) with the
 * `module.exports` line removed, inlined so the generated parser has no
 * `require` and `Wildcard.js` can be deleted from the tree.
 */
const WILDCARD_SOURCE = `
// Wildcard singleton (inlined from sparqljs@3.7.4 lib/Wildcard.js)
class Wildcard {
  constructor() {
    return WILDCARD || this;
  }

  equals(other) {
    return other && (this.termType === other.termType);
  }
}

Object.defineProperty(Wildcard.prototype, 'value', {
  enumerable: true,
  value: '*',
});

Object.defineProperty(Wildcard.prototype, 'termType', {
  enumerable: true,
  value: 'Wildcard',
});

var WILDCARD = new Wildcard();
`;

/** Generates the ESM/TS parser source for the given grammar text (no I/O). */
export function generateParserSource(rawGrammar: string): string {
  const grammar = (parseGrammar as unknown as EbnfParser["parse"])(rawGrammar);
  const generator = new (jison as unknown as JisonModule).Generator(grammar, {
    type: "slr",
    moduleType: "js",
    moduleName: "SparqlParser",
    debug: false,
  });
  const source = generator.generate({
    type: "slr",
    moduleType: "js",
    moduleName: "SparqlParser",
    debug: false,
  });

  // sparqljs's build appends the CommonJS export line to jison's raw output;
  // append the ESM default export the maintained wrapper imports instead.
  const esm = source.replace(
    "var Wildcard = require('./Wildcard').Wildcard;",
    WILDCARD_SOURCE,
  );

  // Generated code is not hand-maintained: skip type checking and linting so
  // deno.json needs no excludes for this file.
  return (
    "// @ts-nocheck\n" +
    "// deno-lint-ignore-file\n" +
    "// Generated by `deno task parser:generate` — edit sparql.jison instead.\n" +
    esm +
    "export default SparqlParser;\n"
  );
}

/**
 * formatWithDenoFmt formats a source string with the project's `deno fmt`
 * rules (via a throwaway temp file), so the checked-in artifact is
 * fmt-stable and regeneration reproduces it byte-for-byte.
 */
async function formatWithDenoFmt(source: string): Promise<string> {
  // The temp file lives in the OS temp dir (not the repo, where a crashed run
  // would leak it into fmt:check and git status), and fileURLToPath is unused:
  // Deno.makeTempFile already returns a platform-native path (URL.pathname is
  // a POSIX-style `/C:/...` string that the Windows CLI mangles).
  const tempPath = await Deno.makeTempFile({
    prefix: "parser-fmt-",
    suffix: ".ts",
  });
  await Deno.writeTextFile(tempPath, source);
  try {
    const cmd = new Deno.Command(Deno.execPath(), {
      args: ["fmt", tempPath],
    });
    const { code, stderr } = await cmd.output();
    if (code !== 0) {
      throw new Error(
        `deno fmt failed: ${new TextDecoder().decode(stderr)}`,
      );
    }
    return await Deno.readTextFile(tempPath);
  } finally {
    await Deno.remove(tempPath);
  }
}

async function main(): Promise<void> {
  const rawGrammar = await Deno.readTextFile(GRAMMAR_PATH);
  const formatted = await formatWithDenoFmt(generateParserSource(rawGrammar));

  if (Deno.args.includes("--check")) {
    const current = await Deno.readTextFile(OUTPUT_PATH);
    if (current !== formatted) {
      console.error(
        "parser.ts is out of date with sparql.jison. " +
          "Run `deno task parser:generate` and commit the result.",
      );
      Deno.exit(1);
    }
    console.log("parser.ts is up to date with sparql.jison.");
    return;
  }

  await Deno.writeTextFile(OUTPUT_PATH, formatted);
  console.log(`Generated parser.ts (${formatted.length} bytes)`);
}

if (import.meta.main) {
  await main();
}
